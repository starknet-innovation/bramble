/**
 * Renders the mobile wallet's generated sources from the single-sourced TypeScript design system
 * and network catalog. The native apps and the Rust core never restate a colour, a scale step, a
 * chain id, or a token address by hand: they read the files this module renders, and
 * `tests/conformance/mobile-generated.test.ts` fails when a committed copy drifts from it.
 *
 * Pure: no I/O. `scripts/generate-mobile-assets.ts` is the writer.
 */
