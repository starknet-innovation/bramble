import { darkSkin } from "@bramble/ui-kit/dark-skin";
import { defaultSkin } from "@bramble/ui-kit/default-skin";
import { SKIN_TOKENS, type Skin, type SkinToken } from "@bramble/ui-kit/skin";
import {
  CONTROL,
  EASE,
  MOTION,
  RADIUS,
  SHADOW,
  SIZE,
  SPACE,
  SPRING,
  TRACKING,
  TYPE,
  WEIGHT,
} from "@bramble/ui-kit/tokens";
import { DEFAULT_TOKENS, STARKNET_NETWORKS } from "@bramble/wallet-model/networks";

/** Repository-relative path of the Swift design tokens consumed by the iOS app. */
export const SWIFT_TOKENS_PATH = "mobile/ios/Bramble/DesignSystem/BrambleTokens.generated.swift";
/** Repository-relative path of the Kotlin design tokens consumed by the Android app. */
export const KOTLIN_TOKENS_PATH =
  "mobile/android/app/src/main/java/org/bramble/wallet/design/BrambleTokens.generated.kt";
/** Repository-relative directory of the iOS brand-mark vector asset. */
export const IOS_MARK_DIR = "mobile/ios/Bramble/Resources/Assets.xcassets/BrandMark.imageset";
/** Repository-relative path of the Android brand-mark vector drawable. */
export const ANDROID_MARK_PATH = "mobile/android/app/src/main/res/drawable/brand_mark.xml";
/** Repository-relative path of the network catalog the Rust core embeds at compile time. */
export const NETWORKS_JSON_PATH = "mobile/core/generated/networks.json";

const HEADER = "Generated by scripts/generate-mobile-assets.ts from packages/*. Do not edit.";
const MOBILE_NETWORK_IDS = ["SN_MAIN", "SN_SEPOLIA"] as const;

const px = (value: string): number => {
  const match = /^(-?\d+(?:\.\d+)?)px$/.exec(value);
  if (!match?.[1]) {
    throw new Error(`Expected a px value, got ${value}`);
  }
  return Number(match[1]);
};

const em = (value: string): number => (value === "0" ? 0 : Number(value.replace(/em$/, "")));

const bezier = (value: string): readonly [number, number, number, number] => {
  const match = /^cubic-bezier\(([^)]+)\)$/.exec(value);
  const parts = match?.[1]?.split(",").map((part) => Number(part.trim())) ?? [];
  if (parts.length !== 4 || parts.some((part) => Number.isNaN(part))) {
    throw new Error(`Expected a cubic-bezier, got ${value}`);
  }
  return [parts[0] ?? 0, parts[1] ?? 0, parts[2] ?? 0, parts[3] ?? 0];
};

type Shadow = { readonly alpha: number; readonly blur: number; readonly y: number };
const shadow = (value: string): Shadow => {
  const match = /^0 (-?\d+)px (\d+)px hsl\(0 0% 0% \/ ([\d.]+)\)$/.exec(value);
  if (!match?.[1] || !match[2] || !match[3]) {
    throw new Error(`Unsupported shadow ${value}`);
  }
  return { alpha: Number(match[3]), blur: Number(match[2]), y: Number(match[1]) };
};

const camel = (token: SkinToken): string =>
  token.replace(/^--bramble-/, "").replace(/-(\w)/g, (_, letter: string) => letter.toUpperCase());

const rgb = (hex: string): string => {
  if (!/^#[0-9a-f]{6}$/.test(hex)) {
    throw new Error(`Skin colours must be #rrggbb, got ${hex}`);
  }
  return hex.slice(1).toUpperCase();
};

// Token keys that are Swift keywords are escaped rather than renamed, so names stay aligned.
const SWIFT_KEYWORDS = new Set(["default", "in", "is", "as", "case", "static"]);
const swiftName = (key: string): string => (SWIFT_KEYWORDS.has(key) ? `\`${key}\`` : key);

const sorted = <T>(record: Readonly<Record<string, T>>): [string, T][] =>
  Object.entries(record).sort(([a], [b]) => a.localeCompare(b));

const swiftSkin = (skin: Skin, name: string): string =>
  [
    `    static let ${name} = BrambleSkin(`,
    `        name: "${skin.name}",`,
    ...SKIN_TOKENS.map(
      (token, index) =>
        `        ${camel(token)}: Color(rgb: 0x${rgb(skin.tokens[token])})${index === SKIN_TOKENS.length - 1 ? "" : ","}`,
    ),
    "    )",
  ].join("\n");

const renderSwift = (): string => {
  const lines: string[] = [
    `// ${HEADER}`,
    "import SwiftUI",
    "",
    "/// Colour skin contract mirrored from `packages/presentation/ui-kit/src/theme/skin.ts`.",
    "struct BrambleSkin: Equatable {",
    "    let name: String",
    ...SKIN_TOKENS.map((token) => `    let ${camel(token)}: Color`),
    "}",
    "",
    "extension BrambleSkin {",
    swiftSkin(defaultSkin, "daylight"),
    "",
    swiftSkin(darkSkin, "midnight"),
    "}",
    "",
    "/// Scale tokens mirrored from `packages/presentation/ui-kit/src/theme/tokens.ts`.",
    "enum BrambleSpace {",
    ...sorted(SPACE).map(([key, value]) => `    static let ${key}: CGFloat = ${px(value)}`),
    "}",
    "",
    "enum BrambleRadius {",
    ...sorted(RADIUS).map(([key, value]) => `    static let ${key}: CGFloat = ${px(value)}`),
    "}",
    "",
    "enum BrambleControl {",
    ...sorted(CONTROL).map(([key, value]) => `    static let ${key}: CGFloat = ${px(value)}`),
    "}",
    "",
    "enum BrambleSize {",
    ...sorted(SIZE).map(([key, value]) => `    static let ${key}: CGFloat = ${px(value)}`),
    "}",
    "",
    "enum BrambleTypeScale {",
    ...sorted(TYPE).map(
      ([key, value]) =>
        `    static let ${key} = BrambleTypeStyle(size: ${px(value.size)}, lineHeight: ${value.line})`,
    ),
    "}",
    "",
    "/// CSS font-weight numbers; `BrambleTheme` maps them onto platform weights.",
    "enum BrambleWeight {",
    ...sorted(WEIGHT).map(([key, value]) => `    static let ${key} = ${value}`),
    "}",
    "",
    "/// Letter-spacing in em; multiply by the point size for kerning.",
    "enum BrambleTracking {",
    ...sorted(TRACKING).map(([key, value]) => `    static let ${key}: CGFloat = ${em(value)}`),
    "}",
    "",
    "enum BrambleMotion {",
    ...sorted(MOTION)
      .filter(([key]) => key.endsWith("Ms"))
      .map(([key, value]) => `    static let ${key}: Double = ${value}`),
    "}",
    "",
    "enum BrambleEase {",
    ...sorted(EASE).map(
      ([key, value]) => `    static let ${key} = BrambleBezier(${bezier(value).join(", ")})`,
    ),
    "}",
    "",
    "enum BrambleSpring {",
    ...sorted(SPRING).map(
      ([key, value]) =>
        `    static let ${swiftName(key)} = Animation.spring(response: ${value.response}, dampingFraction: ${value.damping})`,
    ),
    "}",
    "",
    "enum BrambleShadow {",
    ...sorted(SHADOW).map(([key, value]) => {
      const { alpha, blur, y } = shadow(value);
      return `    static let ${key} = BrambleShadowStyle(y: ${y}, blur: ${blur}, alpha: ${alpha})`;
    }),
    "}",
    "",
  ];
  return lines.join("\n");
};

const kotlinSkin = (skin: Skin, name: string): string =>
  [
    `    val ${name} = BrambleSkin(`,
    `        name = "${skin.name}",`,
    ...SKIN_TOKENS.map(
      (token) => `        ${camel(token)} = Color(0xFF${rgb(skin.tokens[token])}),`,
    ),
    "    )",
  ].join("\n");

const kotlinObject = (name: string, entries: string[]): string[] => [
  `object ${name} {`,
  ...entries,
  "}",
  "",
];

const renderKotlin = (): string => {
  const lines: string[] = [
    `// ${HEADER}`,
    "package org.bramble.wallet.design",
    "",
    "import androidx.compose.animation.core.CubicBezierEasing",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.unit.dp",
    "import androidx.compose.ui.unit.sp",
    "",
    "/** Colour skin contract mirrored from `packages/presentation/ui-kit/src/theme/skin.ts`. */",
    "data class BrambleSkin(",
    "    val name: String,",
    ...SKIN_TOKENS.map((token) => `    val ${camel(token)}: Color,`),
    ")",
    "",
    ...kotlinObject("BrambleSkins", [
      kotlinSkin(defaultSkin, "daylight"),
      "",
      kotlinSkin(darkSkin, "midnight"),
    ]),
    ...kotlinObject(
      "BrambleSpace",
      sorted(SPACE).map(([key, value]) => `    val ${key} = ${px(value)}.dp`),
    ),
    ...kotlinObject(
      "BrambleRadius",
      sorted(RADIUS).map(([key, value]) => `    val ${key} = ${px(value)}.dp`),
    ),
    ...kotlinObject(
      "BrambleControl",
      sorted(CONTROL).map(([key, value]) => `    val ${key} = ${px(value)}.dp`),
    ),
    ...kotlinObject(
      "BrambleSize",
      sorted(SIZE).map(([key, value]) => `    val ${key} = ${px(value)}.dp`),
    ),
    ...kotlinObject(
      "BrambleTypeScale",
      sorted(TYPE).map(
        ([key, value]) =>
          `    val ${key} = BrambleTypeStyle(size = ${px(value.size)}.sp, lineHeight = ${value.line}f)`,
      ),
    ),
    ...kotlinObject(
      "BrambleWeight",
      sorted(WEIGHT).map(([key, value]) => `    const val ${key} = ${value}`),
    ),
    ...kotlinObject(
      "BrambleTracking",
      sorted(TRACKING).map(([key, value]) => `    const val ${key} = ${em(value)}f`),
    ),
    ...kotlinObject(
      "BrambleMotion",
      sorted(MOTION)
        .filter(([key]) => key.endsWith("Ms"))
        .map(([key, value]) => `    const val ${key} = ${value}`),
    ),
    ...kotlinObject(
      "BrambleEase",
      sorted(EASE).map(
        ([key, value]) => `    val ${key} = CubicBezierEasing(${bezier(value).join("f, ")}f)`,
      ),
    ),
    ...kotlinObject(
      "BrambleSpring",
      sorted(SPRING).map(
        ([key, value]) =>
          `    val ${key} = BrambleSpringSpec(response = ${value.response}f, damping = ${value.damping}f)`,
      ),
    ),
    ...kotlinObject(
      "BrambleShadow",
      sorted(SHADOW).map(([key, value]) => {
        const { alpha, blur, y } = shadow(value);
        return `    val ${key} = BrambleShadowStyle(y = ${y}.dp, blur = ${blur}.dp, alpha = ${alpha}f)`;
      }),
    ),
  ];
  return `${lines.join("\n").trimEnd()}\n`;
};

const renderNetworks = (): string => {
  const networks = MOBILE_NETWORK_IDS.map((id) => ({
    chainId: STARKNET_NETWORKS[id].chainId,
    explorerBaseUrl: STARKNET_NETWORKS[id].explorerBaseUrl,
    id,
    name: STARKNET_NETWORKS[id].name,
    rpcUrls: STARKNET_NETWORKS[id].rpcUrls,
    tokens: DEFAULT_TOKENS.filter((token) => token.networkId === id).map((token) => ({
      address: token.address,
      decimals: token.decimals,
      name: token.name,
      symbol: token.symbol,
    })),
  }));
  return `${JSON.stringify({ generatedBy: HEADER, networks }, null, 2)}\n`;
};

const markSize = (): readonly [string, string] => {
  const [, , width, height] = BRAMBLE_MARK_VIEW_BOX.split(" ");
  if (!width || !height) {
    throw new Error("Brand mark view box must be four numbers");
  }
  return [width, height];
};

const renderMarkSvg = (): string => {
  const [width, height] = markSize();
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="${BRAMBLE_MARK_VIEW_BOX}"><title>Bramble</title><path fill="#000000" d="${BRAMBLE_MARK_PATH}"/></svg>\n`;
};

// Template rendering: the platform tints the mark with the skin's text colour, as
// `currentColor` does in the extension.
const renderMarkContents = (): string =>
  `${JSON.stringify(
    {
      images: [{ filename: "mark.svg", idiom: "universal" }],
      info: { author: "xcode", version: 1 },
      properties: {
        "preserves-vector-representation": true,
        "template-rendering-intent": "template",
      },
    },
    null,
    2,
  )}\n`;

const renderMarkDrawable = (): string => {
  const [width, height] = markSize();
  return [
    `<!-- ${HEADER} -->`,
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    `    android:width="${width}dp"`,
    `    android:height="${height}dp"`,
    `    android:viewportWidth="${width}"`,
    `    android:viewportHeight="${height}">`,
    "    <path",
    '        android:fillColor="#FF000000"',
    `        android:pathData="${BRAMBLE_MARK_PATH}" />`,
    "</vector>",
    "",
  ].join("\n");
};

/**
 * Every generated mobile source keyed by repository-relative path. Throws when a token no
 * longer has a shape the native platforms can express, rather than emitting a lossy value.
 */
export const renderMobileAssets = (): ReadonlyMap<string, string> =>
  new Map([
    [SWIFT_TOKENS_PATH, renderSwift()],
    [KOTLIN_TOKENS_PATH, renderKotlin()],
    [NETWORKS_JSON_PATH, renderNetworks()],
    [`${IOS_MARK_DIR}/mark.svg`, renderMarkSvg()],
    [`${IOS_MARK_DIR}/Contents.json`, renderMarkContents()],
    [ANDROID_MARK_PATH, renderMarkDrawable()],
  ]);
