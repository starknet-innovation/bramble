/**
 * Renders the in-app browser's document-start script (P16): `provider/mobile-bridge.ts` (the
 * native seam, standing where the content script stands) followed by the extension's own
 * `provider/inpage.ts`, unchanged, each bundled as the extension build bundles `inpage.ts`. Both
 * apps load the one committed file; `tests/conformance/mobile-generated.test.ts` fails when it
 * drifts from these sources. Run directly, it prints the script: `Bun.build` cannot run inside
 * `bun test` once the test has loaded the same sources, so the test renders it in a subprocess.
 */
import { join } from "node:path";

/** Repository-relative path of the script both apps inject at document start. */
export const MOBILE_PROVIDER_PATH = "mobile/web/bramble-provider.generated.js";

const PROVIDER_ROOT = join(import.meta.dir, "../../apps/extension/src/provider");

const bundle = async (entry: string): Promise<string> => {
  const result = await Bun.build({
    // ponytail: no wallet version in the app's provider; the extension stamps its manifest's, and
    // stamping that here would make every release bump a generated-file drift.
    define: { __MC_BUILD_VERSION__: JSON.stringify("") },
    entrypoints: [join(PROVIDER_ROOT, entry)],
    format: "iife",
    minify: true,
    target: "browser",
  });
  const output = result.outputs[0];
  if (!result.success || !output) {
    throw new Error(`could not bundle ${entry}: ${result.logs.join("\n")}`);
  }
  return (await output.text()).trim();
};

/**
 * The injected script's text. Each part runs only in the top frame: Android's document-start
 * scripts reach every frame, and the hosts refuse any request a subframe sends anyway.
 */
export const renderMobileProvider = async (): Promise<string> => {
  const parts = [await bundle("mobile-bridge.ts"), await bundle("inpage.ts")];
  const guarded = parts.map((part) => `if (window.top === window) {\n${part}\n}`);
  return `// Generated by scripts/generate-mobile-assets.ts from apps/extension/src/provider. Do not edit.\n${guarded.join("\n")}\n`;
};

if (import.meta.main) {
  process.stdout.write(await renderMobileProvider());
}
