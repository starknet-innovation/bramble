/**
 * Assembles the mobile privacy fixture (docs/privacy.md §6) from the extension's production code.
 * Shared by the generator (`generate-mobile-privacy-vectors.ts`) and the drift test in
 * `tests/conformance/mobile-generated.test.ts`, so both compute exactly the same documents.
 *
 * Committed as three files, each within the 500-line limit: rows are stored one compact JSON
 * string per line, and readers decode them (`mobile/core/tests/privacy_support`,
 * `BrambleTests/PrivacyTestSupport.swift`).
 */
import { DEFAULT_STRK20_NETWORKS } from "@bramble/privacy/config";
import { renderPrivacyRouting } from "./mobile-assets/privacy";
import { PARITY_MNEMONIC } from "./mobile-parity";
import { computePrivacyCopy } from "./mobile-privacy-copy";
import { computeGates } from "./mobile-privacy-gates";
import { computeViewingKeys, computeWire } from "./mobile-privacy-wire";

const GENERATED_BY =
  "Generated by scripts/generate-mobile-privacy-vectors.ts from the extension's privacy path. Do not edit.";

/** Repository-relative paths of the three committed fixture files. */
export const PRIVACY_FIXTURE_PATHS = {
  copy: "mobile/core/tests/fixtures/extension-privacy-copy.json",
  rules: "mobile/core/tests/fixtures/extension-privacy-rules.json",
  wire: "mobile/core/tests/fixtures/extension-privacy-wire.json",
} as const;

const rows = (values: readonly unknown[]): string[] => values.map((value) => JSON.stringify(value));

const mainnet = DEFAULT_STRK20_NETWORKS.SN_MAIN;

/** Fixture 2: the bundled routing and two OHTTP configs that must not be routed. */
const computeRouting = () => {
  if (!mainnet) throw new Error("mainnet privacy routing missing");
  return {
    bundled: renderPrivacyRouting(),
    ohttpEnabled: renderPrivacyRouting({ SN_MAIN: { ...mainnet, ohttpEnabled: true } }),
    ohttpRelay: renderPrivacyRouting({
      SN_MAIN: { ...mainnet, ohttpEnabled: false, ohttpRelayUrl: "https://relay.example" },
    }),
  };
};

/** The three fixture documents, keyed by path, as plain JSON data. */
export const computePrivacyFixture = async (): Promise<ReadonlyMap<string, unknown>> => {
  // The wire capture swaps `fetch`; it runs before the gate capture registers a DOM.
  const viewingKeys = await computeViewingKeys();
  const wire = await computeWire();
  const gates = await computeGates();
  const copy = computePrivacyCopy(gates);
  const plain = (value: unknown): unknown => JSON.parse(JSON.stringify(value));
  return new Map<string, unknown>([
    [
      PRIVACY_FIXTURE_PATHS.wire,
      plain({
        capture: rows(wire.capture.requests),
        cases: rows(wire.cases),
        discoveryUrl: wire.capture.discoveryUrl,
        generatedBy: GENERATED_BY,
        mnemonic: PARITY_MNEMONIC,
        routing: computeRouting(),
        viewingKeys,
      }),
    ],
    [
      PRIVACY_FIXTURE_PATHS.rules,
      plain({
        compactAmounts: rows(gates.compactAmounts),
        generatedBy: GENERATED_BY,
        journeys: rows(gates.journeys),
        privateEth: gates.privateEth,
        static: rows(gates.static),
        unified: rows(gates.unified),
      }),
    ],
    [PRIVACY_FIXTURE_PATHS.copy, plain({ copy, generatedBy: GENERATED_BY })],
  ]);
};
