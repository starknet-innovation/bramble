/**
 * Assembles the mobile transaction fixture from the extension's production code. Shared by the
 * generator and by the drift test in `tests/conformance/mobile-generated.test.ts`, so both compute
 * exactly the same document.
 */

import {
  computeCallVectors,
  computeFeeVectors,
  computeObservationVectors,
  computePresentationVectors,
  computeStatusVectors,
  computeTimingVectors,
} from "./mobile-transactions";
import {
  argentFailureCopy,
  captureArgentRefusals,
  captureArgentScenarios,
} from "./mobile-transactions-argent";
import {
  braavosFailureCopy,
  captureBraavosRefusals,
  captureBraavosScenarios,
} from "./mobile-transactions-braavos";
import {
  captureFailureCopy,
  captureTransactionScenarios,
  TRANSACTION_AMOUNT,
  TRANSACTION_MNEMONIC,
} from "./mobile-transactions-capture";
import { computeCopyVectors } from "./mobile-transactions-copy";
import { computeScreenCopy } from "./mobile-transactions-screens";

/** The whole fixture as plain JSON data (bigints already rendered as strings). */
export const computeTransactionFixture = async (): Promise<unknown> => {
  const argentRefusals = await captureArgentRefusals();
  const braavosRefusals = await captureBraavosRefusals();
  return JSON.parse(
    JSON.stringify({
      amount: TRANSACTION_AMOUNT,
      argent: { refusals: argentRefusals, scenarios: await captureArgentScenarios() },
      braavos: { refusals: braavosRefusals, scenarios: await captureBraavosScenarios() },
      calls: computeCallVectors(),
      copy: {
        ...computeCopyVectors(),
        failures: {
          ...(await captureFailureCopy()),
          ...argentFailureCopy(argentRefusals),
          ...braavosFailureCopy(braavosRefusals),
        },
        screens: computeScreenCopy(),
      },
      fees: computeFeeVectors(),
      generatedBy:
        "Generated by scripts/generate-mobile-transaction-vectors.ts from the extension's send path. Do not edit.",
      mnemonic: TRANSACTION_MNEMONIC,
      observation: computeObservationVectors(),
      presentation: computePresentationVectors(),
      scenarios: await captureTransactionScenarios(),
      status: await computeStatusVectors(),
      timing: computeTimingVectors(),
    }),
  );
};

type Scenario = Record<string, unknown>;

type Fixture = Record<string, unknown> & {
  readonly argent: {
    readonly refusals: readonly Scenario[];
    readonly scenarios: readonly Scenario[];
  };
  readonly braavos: {
    readonly refusals: readonly Scenario[];
    readonly scenarios: readonly Scenario[];
  };
  readonly scenarios: readonly Scenario[];
};

// Ready records at the class this wallet deploys, as opposed to older records upgraded to it.
const isPinnedRelease = (scenario: Scenario): boolean => scenario["recordClass"] === "argent 0.4.0";

const WIRE_PHASES = ["reviewInvoke", "reviewDeployment", "submit"] as const;

// One compact JSON string per wire exchange, so a scenario stays a few lines per request.
const compactWire = (scenario: Scenario): Scenario => ({
  ...scenario,
  ...Object.fromEntries(
    WIRE_PHASES.map((phase) => [
      phase,
      (scenario[phase] as readonly unknown[]).map((exchange) => JSON.stringify(exchange)),
    ]),
  ),
});

/**
 * The fixture as committed: ten files, each within the repository's 500-line limit. Wire
 * exchanges are stored one compact JSON string per line; readers decode them
 * (`mobile/core/tests/send_support`, `BrambleTests/SendTestSupport.swift`).
 */
export const splitTransactionFixture = (whole: unknown): ReadonlyMap<string, unknown> => {
  const fixture = whole as Fixture;
  const file = (part: string) => `mobile/core/tests/fixtures/extension-transactions-${part}.json`;
  return new Map<string, unknown>([
    [
      file("wire"),
      {
        amount: fixture["amount"],
        generatedBy: fixture["generatedBy"],
        mnemonic: fixture["mnemonic"],
        scenarios: fixture.scenarios.map(compactWire),
      },
    ],
    [
      file("argent"),
      {
        generatedBy:
          "Generated by scripts/generate-mobile-transaction-vectors.ts from the extension's Ready (Argent) send path (scripts/mobile-transactions-argent.ts). Do not edit.",
        mnemonic: fixture["mnemonic"],
        scenarios: fixture.argent.scenarios.filter(isPinnedRelease).map(compactWire),
      },
    ],
    [
      file("argent-upgraded"),
      {
        scenarios: fixture.argent.scenarios
          .filter((scenario) => !isPinnedRelease(scenario))
          .map(compactWire),
      },
    ],
    [file("argent-refusals"), { refusals: fixture.argent.refusals.map(compactWire) }],
    [
      file("braavos"),
      {
        generatedBy:
          "Generated by scripts/generate-mobile-transaction-vectors.ts from the extension's Braavos send and deployment path (scripts/mobile-transactions-braavos.ts). Do not edit.",
        scenarios: fixture.braavos.scenarios.map(compactWire),
      },
    ],
    [file("braavos-refusals"), { refusals: fixture.braavos.refusals.map(compactWire) }],
    [file("rules"), { calls: fixture["calls"], fees: fixture["fees"], timing: fixture["timing"] }],
    [file("presentation"), { presentation: fixture["presentation"] }],
    [file("status"), { status: fixture["status"] }],
    [file("observation"), { observation: fixture["observation"] }],
    [file("copy"), { copy: fixture["copy"] }],
  ]);
};
