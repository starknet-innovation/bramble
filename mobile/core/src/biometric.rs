//! Opt-in biometric unlock. The vault's DEK is additionally wrapped under a 32-byte wrap secret W
//! that the host generates with its CSPRNG and keeps behind the platform's biometric hardware
//! (iOS Keychain `.biometryCurrentSet`; Android Keystore with user authentication). W only ever
//! flows host → core; the DEK never leaves Rust.
//!
//! Biometrics never replace the passphrase: enabling needs it, revealing the phrase always needs
//! it, and a biometric success does not reset the passphrase backoff. The slot is dropped only on
//! a real enrolment change or a slot W no longer opens; an ordinary non-match, cancel or lockout is
//! handled by the host as "offer the passphrase" and never reaches these methods as a failure.

use std::sync::atomic::Ordering;

use zeroize::Zeroizing;

use crate::container::{self, StoredVault};
use crate::files::storage;
use crate::migrations::Opened;
use crate::wallet::{expire, WalletCore};
use crate::CoreError;

/// What the host could learn about biometric enrolment right now.
#[derive(Debug, Clone, PartialEq, Eq, uniffi::Enum)]
pub enum BiometricDomain {
    /// Biometrics temporarily unusable (lockout after non-matches, no domain-state API on the
    /// platform, policy evaluation failed for any other reason). Keeps the slot.
    Unavailable,
    /// Every face or finger was removed: a real enrolment change. Drops the slot.
    NotEnrolled,
    /// The current domain state (iOS `evaluatedPolicyDomainState`), only reported when policy
    /// evaluation succeeded. A different state than at enrolment drops the slot.
    State { value: Vec<u8> },
}

fn wrap_secret(bytes: Vec<u8>) -> Result<Zeroizing<[u8; 32]>, CoreError> {
    let bytes = Zeroizing::new(bytes);
    let mut secret = Zeroizing::new([0u8; 32]);
    if bytes.len() != secret.len() {
        return Err(CoreError::InvalidInput {
            reason: "wrap secret must be 32 bytes".into(),
        });
    }
    secret.copy_from_slice(&bytes);
    Ok(secret)
}

impl WalletCore {
    /// Removes the biometric slot, only if it is still the one `expected_id` names (when given),
    /// so a stale failure cannot remove a slot enabled since. Needs no key.
    fn drop_biometric_slot(&self, expected_id: Option<&str>) -> Result<(), CoreError> {
        let _file = self.lock_file();
        let mut file = match self.read_vault() {
            Ok(StoredVault::V2(file)) => file,
            Ok(StoredVault::V1(_)) | Err(CoreError::NoWallet) => return Ok(()),
            Err(error) => return Err(error),
        };
        match (&file.biometric_slot, expected_id) {
            (None, _) => return Ok(()),
            (Some(slot), Some(id)) if slot.id != id => return Ok(()),
            _ => {}
        }
        file.biometric_slot = None;
        self.write_vault(&file)
    }
}

#[uniffi::export]
impl WalletCore {
    /// Re-checks the passphrase (throttled and counted), then wraps the DEK under `wrap_secret`
    /// (exactly 32 host-generated bytes, which the host wipes after the call) and stores the slot,
    /// replacing any earlier one. `domain_state` is the host's biometric domain state at
    /// enrolment, or `None` on a platform without one. Never returns key material.
    pub fn enable_biometric_unlock(
        &self,
        password: String,
        wrap_secret: Vec<u8>,
        domain_state: Option<Vec<u8>>,
    ) -> Result<(), CoreError> {
        let password = Zeroizing::new(password);
        let secret = self::wrap_secret(wrap_secret)?;
        let domain = domain_state
            .map(|state| container::domain_hash(&state))
            .unwrap_or_default();
        self.passphrase_attempt(&password, |opened: Opened| {
            let mut session = self.lock_session();
            expire(&mut session, &self.now());
            let _file = self.lock_file();
            let (mut base, dek) = match self.read_vault()? {
                StoredVault::V2(file) if file.password_slot == opened.container.password_slot => {
                    (*file, opened.dek)
                }
                StoredVault::V1(_) => match session.as_ref().and_then(|s| s.pending.clone()) {
                    Some(pending) => {
                        let dek = session
                            .as_ref()
                            .map(|s| s.dek.clone())
                            .unwrap_or(opened.dek);
                        (pending, dek)
                    }
                    None => (opened.container, opened.dek),
                },
                StoredVault::V2(_) => return Err(storage("vault changed on disk")),
            };
            base.biometric_slot = Some(base.seal_biometric(&dek, &secret, domain)?);
            self.write_vault(&base)?;
            // Keep a live session consistent with the file just written, and renew it.
            if let Some(live) = session.as_mut() {
                live.password_slot = base.password_slot.clone();
                live.dek = dek;
                live.pending = None;
                live.last_activity = self.now();
            }
            Ok(())
        })
    }

    /// Removes the biometric slot. Needs no key, so it works while locked; anyone able to call it
    /// can only turn biometrics off. The host deletes its Keychain item or Keystore key too.
    pub fn disable_biometric_unlock(&self) -> Result<(), CoreError> {
        self.drop_biometric_slot(None)
    }

    /// Unwraps the DEK with the wrap secret the platform released after a biometric match and
    /// opens the session. `BiometricUnavailable` when no slot exists; when W does not open the
    /// slot it is stale, so the slot is dropped and `BiometricInvalidated` returned. Not counted
    /// against the passphrase backoff (W cannot be guessed) and does not reset it.
    pub fn unlock_with_biometric(&self, wrap_secret: Vec<u8>) -> Result<(), CoreError> {
        let secret = self::wrap_secret(wrap_secret)?;
        let epoch = self.lock_epoch.load(Ordering::SeqCst);
        let StoredVault::V2(file) = self.read_vault()? else {
            return Err(CoreError::BiometricUnavailable);
        };
        let dek = match file.open_biometric(&secret) {
            Err(CoreError::BiometricInvalidated) => {
                let id = file.biometric_slot.as_ref().map(|slot| slot.id.as_str());
                self.drop_biometric_slot(id)?;
                return Err(CoreError::BiometricInvalidated);
            }
            other => other?,
        };
        let payload = file.open_payload(&dek)?;
        let opened = Opened {
            payload,
            dek,
            container: *file,
            migrated: false,
        };
        self.install(epoch, opened, None)
    }

    /// Compares the host's biometric domain with the slot, each time the app becomes active. A
    /// changed `State` or `NotEnrolled` is an enrolment change: the wallet locks, the slot is
    /// dropped, and `BiometricInvalidated` is returned. `Unavailable` changes nothing.
    pub fn reconcile_biometric_domain(&self, domain: BiometricDomain) -> Result<(), CoreError> {
        let file = match self.read_vault() {
            Ok(StoredVault::V2(file)) => file,
            Ok(StoredVault::V1(_)) | Err(CoreError::NoWallet) => return Ok(()),
            Err(error) => return Err(error),
        };
        let Some(slot) = file.biometric_slot else {
            return Ok(());
        };
        let changed = match domain {
            BiometricDomain::Unavailable => false,
            BiometricDomain::NotEnrolled => true,
            BiometricDomain::State { value } => {
                !slot.domain.is_empty() && container::domain_hash(&value) != slot.domain
            }
        };
        if !changed {
            return Ok(());
        }
        self.lock();
        self.drop_biometric_slot(Some(&slot.id))?;
        Err(CoreError::BiometricInvalidated)
    }

    /// The platform reported a permanent invalidation (Android `KeyPermanentlyInvalidatedException`,
    /// iOS `errSecItemNotFound`): locks and drops the slot.
    pub fn biometric_invalidated(&self) -> Result<(), CoreError> {
        self.lock();
        self.drop_biometric_slot(None)
    }
}
