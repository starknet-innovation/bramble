/**
 * Writes `mobile/android/app/src/test/resources/qr-parity.txt`: the extension's own QR matrices
 * (`shared/qr.ts`) for a few inputs, which `QrCodeTest` compares with the Kotlin port module for
 * module. Regenerate after changing either encoder: `bun mobile/android/scripts/qr-fixture.ts`.
 * The file is generated, never edited by hand.
 */
import { writeFile } from "node:fs/promises";
import { qrMatrix } from "../../../packages/presentation/wallet-ui/src/sidepanel/shared/qr";

const OUTPUT = "mobile/android/app/src/test/resources/qr-parity.txt";

// The repository's published E2E address, a full 66-character felt, and inputs on each side of
// the version-1 capacity (14 bytes) and of the 16-bit length field (version 10).
const INPUTS = [
  "0x208361e3911b1d93a704400b88e7e53a89171fce64dbb48f8479e4f44b398d9",
  "0x049d36570d4e46f48e99674bd3fcc84644ddd6b96f7c741b1562b82f9e004dc7",
  "bramble-qr-v1!",
  "bramble-qr-v2!!",
  "starknet:".repeat(22),
] as const;

const lines = [
  "# Generated by mobile/android/scripts/qr-fixture.ts from shared/qr.ts. Do not edit.",
];
for (const input of INPUTS) {
  lines.push(`input ${input}`);
  for (const row of qrMatrix(input)) {
    lines.push(`row ${row.map((dark) => (dark ? "1" : "0")).join("")}`);
  }
}
await writeFile(OUTPUT, `${lines.join("\n")}\n`);
console.log(`wrote ${INPUTS.length} QR matrices to ${OUTPUT}`);
